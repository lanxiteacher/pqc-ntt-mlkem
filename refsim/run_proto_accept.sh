#!/bin/sh
# ===========================================================================
# run_proto_accept.sh —— proto.md §5.5 末尾「三条注入错误」的验收入口
#
# 它是**调度器，不是测试**：一条断言都不重写，只把已经存在的自测按 §5.5 的
# 原话映射过来跑一遍，再把结论打出来。
#
# 为什么要它：这三条以前散在三个文件里（见下面「落在哪」），没有单一入口，
# 也没映射到 §5.5 的原话 —— 于是「到底跑过没有」只能靠人记。这个脚本把那个
# 「记」变成一条命令，且结论可复跑、可给别人跑。
#
# §5.5「冻结前的验收方式」原文三条：
#   ① 发半行就停          -> 板子侧应在 T_LINE 后回 #ERR 05，而不是卡死
#   ② 发错一个字符        -> 应回 #ERR 04（或 #ERR 03）并报出位置
#   ③ 收到命令后故意不回  -> 电脑侧应在 T_OK 超时、发 #ABORT、重发一次、
#                            再超时后**干净退出而不是卡死**
#
# 落在哪（这是本脚本的全部智能，没有第二份断言）：
#   ① test_fake_board_data.py 第 6b    ② test_fake_board_data.py 第 6a
#                                       ② test_fake_board.py     第 2（#ERR 03）
#   ③ test_host.py 第 2 / 3 / 4
#
# 判据是**两条一起看，缺一不可**：
#   (a) 被调脚本**退出码为 0**      —— 这是「过了」的判据；
#   (b) 下面每条标记**确实出现**    —— 这是「这条真的跑了」的判据。
#       标记要挑**带结果的**行（如「试了 2 次」「等不到任何应答」），
#       **不要**挑无条件打印的小节横幅 —— 横幅只证明「这一节开了头」，
#       开了头当场挂掉也算开了头。
# 标记找不到就**响亮失败**，绝不当通过。理由：脚本或输出格式被改动后，
# 这里的 grep 会落空 —— 那时正因为落空而报警，才不会变成又一处「假绿」
# （本项目在 CRLF、$readmemh 空向量、行号引用上已经各咬过一次）。
# 另：一组都没跑到（NCHECK=0）也算**失败**，见文末的防呆块。
#
# 用法：sh refsim/run_proto_accept.sh
# 依赖：python。**不需要 iverilog、不需要板子、不需要联网。**
#
# ⚠️ 覆盖范围的实话：跑的是**陪练** host/src/fake_board.py，**不是** A 的真 RTL。
#    真板子侧的 ①② 归 rtl/board/tb/uart_proto_tb.v（B 接手后按 §六第 12 条
#    挪到 refsim/）。本脚本通过 ≠ 真板子通过。
# ===========================================================================

HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="$HERE/../host/src"
cd "$SRC" || { echo "!! 进不去 $SRC"; exit 1; }

FAILS=0
NCHECK=0

# 跑一个脚本：要求退出码为 0，且输出里含**全部** marker。
# 用法：run <脚本名> <给谁看的一句话> <marker>...
run() {
    script="$1"; shift
    label="$1";  shift
    NCHECK=$((NCHECK + 1))

    out="$(PYTHONIOENCODING=utf-8 python "$script" 2>&1)"
    rc=$?                       # ⚠️ 先接住退出码再动别处 —— 别写成 `... | 别的命令` 再取 $?

    if [ "$rc" -ne 0 ]; then
        printf '%s\n' "$out" | tail -20
        echo "  ✗ $label —— $script 退出码 $rc（不是 0）"
        FAILS=$((FAILS + 1))
        return
    fi

    for m in "$@"; do
        if ! printf '%s\n' "$out" | grep -qF -- "$m"; then
            echo "  ✗ $label —— $script 退出码是 0，但输出里找不到标记："
            echo "        $m"
            echo "     这条用例的**证据不见了** —— 不许当通过。"
            FAILS=$((FAILS + 1))
            return
        fi
    done

    echo "  ✓ $label    【$script 退出码 0；标记 $# 条全在】"
}

echo "==================================================================="
echo " §5.5 三条注入错误 —— 验收（调度器：不重写断言，只映射 + 核验）"
echo " cwd=$SRC"
echo "==================================================================="
echo

echo "① 发半行就停 → 板子侧在 T_LINE 后回 #ERR 05，不卡死"
run test_fake_board_data.py "① 数据段收 7 行后超时" \
    "T_LINE 超时 -> #ERR 05 7"
echo

echo "② 发错一个字符 → #ERR 04（或 #ERR 03）并报出位置"
run test_fake_board_data.py "②a 数据行错一个字符（位置 = 非法字符的列号）" \
    "'0g4'" "#ERR 04 2"
run test_fake_board.py     "②b 命令行校验错（#ERR 03 带 got= / exp=）" \
    "#ERR 03 got=3f exp=a2"
echo

echo "③ 收到命令后故意不回 → T_OK 超时 → #ABORT → 重发 → 干净退出不卡死"
run test_host.py "③ 超时重发 / 重发上限 / 链路死了停整轮" \
    "=== 2：超时" "试了 2 次" \
    "=== 3：重试有上限" "试了 4 次" \
    "=== 4：链路真的死了" "等不到任何应答"
echo

echo "-------------------------------------------------------------------"

# 防呆：「一组都没跑」也是假绿 —— 零检查必须是**失败**，不许当通过。
# （同 test_citations.py 的规矩：一条引用都找不到就 exit 1，而不是报平安。
#   映射表写坏、脚本被改名、路径变了，都会让 NCHECK 停在这里 = 0。）
if [ "$NCHECK" -eq 0 ]; then
    echo "✗ 一组检查都没跑到（NCHECK=0）—— 调度器的映射表坏了。"
    echo "  「零组通过」不是通过，**不许**当成功。"
    exit 1
fi

if [ "$FAILS" -ne 0 ]; then
    echo "✗ $NCHECK 组里 $FAILS 组不过 —— §5.5 的验收**没有**通过。"
    exit 1
fi
echo "✓ $NCHECK 组全过 —— 三条都在**陪练**上成立。"
echo "  ⚠️ 只到这儿：真 RTL（A 的 uart_proto_tb.v）那侧还没跑，真板子更没跑。"
exit 0
