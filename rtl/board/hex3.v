// ===========================================================================
// hex3.v —— 3 位十六进制字符 ↔ 12 位系数（三个**纯组合**模块，无时钟无状态）
//
// 依据：host/proto.md §5.3.1 —— 一个系数在线上就是**恰好 3 位**十六进制字符。
//   12 位 ÷ 4 位每字符 = 正好 3 个，不多不少（这不是凑出来的土办法）。
//   §5.3.1 还定死：`004` 合法，`4` 和 `04` **不**合法（长度必须正好 3）。
//
// ★ 本仓库统一的「3 字符」摆放 —— 后面每个模块都按这一条，别再倒过来：
//
//     记 r = {c1, c2, c3}，其中 c1 是**先到**的那个字符，则
//         r[23:16] = c1   ← 最高 nibble
//         r[15: 8] = c2
//         r[ 7: 0] = c3   ← 最低 nibble
//
//   也就是**按字符串左对齐**：先到的字符放最高字节。
//   例："044" → r = 24'h30_34_34 → val = 12'h044。
//
// ⚠️ 两个方向**故意不对称**：
//     接收 —— **宽容大写**。proto.md §5.1 写明「A2f = a2f = 2607，不回错、
//             也不要求电脑端改」。这是为了容错。
//     发送 —— **一律小写**。§5.4 细则 3：「全协议只用小写……减少一处两端
//             不一致点」。电脑端也对拍小写文件，大写会让 diff 报「全不同」。
// ===========================================================================

`timescale 1ns/1ps

// ---------------------------------------------------------------------------
// 一个十六进制字符（ASCII 字节）→ 4 位值 + 合法标志
// 合法范围：0-9 / a-f / A-F。其余一律 ok=0。
// ---------------------------------------------------------------------------
module hex_digit (
    input      [7:0] c,
    output reg [3:0] v,
    output reg       ok
);
    always @(*) begin
        case (c)
            8'h30: begin v = 4'h0; ok = 1'b1; end   // '0'
            8'h31: begin v = 4'h1; ok = 1'b1; end   // '1'
            8'h32: begin v = 4'h2; ok = 1'b1; end   // '2'
            8'h33: begin v = 4'h3; ok = 1'b1; end   // '3'
            8'h34: begin v = 4'h4; ok = 1'b1; end   // '4'
            8'h35: begin v = 4'h5; ok = 1'b1; end   // '5'
            8'h36: begin v = 4'h6; ok = 1'b1; end   // '6'
            8'h37: begin v = 4'h7; ok = 1'b1; end   // '7'
            8'h38: begin v = 4'h8; ok = 1'b1; end   // '8'
            8'h39: begin v = 4'h9; ok = 1'b1; end   // '9'
            8'h41, 8'h61: begin v = 4'hA; ok = 1'b1; end   // 'A' / 'a'
            8'h42, 8'h62: begin v = 4'hB; ok = 1'b1; end   // 'B' / 'b'
            8'h43, 8'h63: begin v = 4'hC; ok = 1'b1; end   // 'C' / 'c'
            8'h44, 8'h64: begin v = 4'hD; ok = 1'b1; end   // 'D' / 'd'
            8'h45, 8'h65: begin v = 4'hE; ok = 1'b1; end   // 'E' / 'e'
            8'h46, 8'h66: begin v = 4'hF; ok = 1'b1; end   // 'F' / 'f'
            default:      begin v = 4'h0; ok = 1'b0; end
        endcase
    end
endmodule

// ---------------------------------------------------------------------------
// 3 个字符 → 12 位
// ok = 0 表示三个字符里至少有一个不是十六进制字符（调用方据此报 #ERR 04）
// ---------------------------------------------------------------------------
module hex3_to12 (
    input      [23:0] r,        // 3 个字符，先到的在 [23:16]
    output     [11:0] val,
    output            ok
);
    wire [3:0] v1, v2, v3;
    wire       o1, o2, o3;

    hex_digit d1 (.c(r[23:16]), .v(v1), .ok(o1));
    hex_digit d2 (.c(r[15: 8]), .v(v2), .ok(o2));
    hex_digit d3 (.c(r[ 7: 0]), .v(v3), .ok(o3));

    assign val = {v1, v2, v3};      // 先到的字符是最高 nibble
    assign ok  = o1 & o2 & o3;
endmodule

// ---------------------------------------------------------------------------
// 12 位 → 3 个字符（**一律小写**）
// ---------------------------------------------------------------------------
module hex12_to3 (
    input      [11:0] val,      // 值域 0..3328（q = 3329），12 位足够
    output     [23:0] r         // 先发的在 [23:16]
);
    assign r = { hexchar(val[11:8]), hexchar(val[7:4]), hexchar(val[3:0]) };

    function [7:0] hexchar;
        input [3:0] n;
        begin
            hexchar = (n < 4'd10) ? (8'h30 + n)           // '0'..'9'
                                  : (8'h61 + n - 8'd10);  // 'a'..'f'
        end
    endfunction
endmodule
