// ===========================================================================
// poly_buf.v —— 多项式缓冲（A、B 各 256 个 12 位系数）
//
// ★ 为什么非要有它 —— 这条决定了整个板级架构，不是可选的优化：
//
//   核的 load_* 口**没有「数据有效」选通信号**（rtl/H1_port_spec.md §四实测）：
//   FSM 一旦进了 OP_LOAD_DATA，就**每拍硬写一次 BRAM**，靠内部计数器 di_cntr
//   数满 256 才退出。所以：
//       · 不能逐拍断续给（没有地方挂起）
//       · 不能灌到一半停（计数没满，FSM 一直停在 OP_LOAD_DATA，后续 start_* 不响应）
//       · 灌之前 256 个系数必须**全部就绪**
//
//   而两边的速度差 17,361 倍：
//       串口送一个多项式  4,444,444 拍 = 88.9 ms
//       核灌满一个多项式        256 拍 =  5.12 µs
//
//   于是数据流只能是：
//       UART → [行缓冲 + 十六进制解析] → [本模块] → 核的 din（256 拍 burst）
//
//   ⇒ **先收满整组，再一次性 burst 进核。**「边收边灌」在协议里已判为
//     「不是不划算，是根本做不到」（host/proto.md §六第 3 条，定乙）。
//
// 端口约定：
//   写口 —— 串口每收到一行数据，解析出 12 位后写一个。sel_b 决定写 A 还是 B。
//   读口 —— **组合读**。装载状态机用一个计数器从 0 数到 255 顺序取，一拍一个。
//           （组合读是刻意的：装载必须连续 256 拍不断，中间不能有读延迟的空拍。）
//
// ⚠️ 容量 256 × 12 × 2 = 6144 位。综合会落成 LUTRAM / BRAM，**不占引脚预算**
//    （引脚预算已实测：三档 Bonded IOB 都是 37，见 rtl/vivado/folding_comparison.md）。
// ===========================================================================

`timescale 1ns/1ps

module poly_buf (
    input               clk,

    // ------------------------- 写口（来自串口解析）-------------------------
    input               we,
    input               sel_b,      // 0 = 写 A，1 = 写 B
    input      [7:0]    waddr,      // 0..255
    input      [11:0]   wdata,

    // --------------------- 读口（组合读，给装载状态机）----------------------
    input      [7:0]    raddr,      // 0..255
    output     [11:0]   a_rdata,
    output     [11:0]   b_rdata
);

    reg [11:0] mem_a [0:255];
    reg [11:0] mem_b [0:255];

    always @(posedge clk) begin
        if (we) begin
            if (sel_b) mem_b[waddr] <= wdata;
            else       mem_a[waddr] <= wdata;
        end
    end

    assign a_rdata = mem_a[raddr];
    assign b_rdata = mem_b[raddr];

endmodule
