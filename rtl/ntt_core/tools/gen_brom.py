#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Regenerate rtl/ntt_core/BROM.v from the three upstream BROM.v files.

Why this script exists
----------------------
The twiddle tables are NOT the same across folding configs, and are NOT
packings or contiguous slices of each other (see rtl/folding_param_design.md
section 3.3c, evidence produced by check_brom.py).  So the unified tree cannot
derive one table from another -- it keeps all three verbatim, selected by a
`generate` on PE_NUMBER.

Copying 708 lines of `case` by hand invites transcription errors that no
compiler and no synthesis run will catch.  This script extracts each `case`
block character-for-character from the upstream file and emits the three
generate branches.  Run check_brom.py afterwards to prove the extraction.

Dependency: reads rtl/pe{1,4,16}/BROM.v.  Those trees are being superseded by
rtl/ntt_core/; if they are ever removed, point --src-root at the read-only
originals under research/ref_rtl/kyber-polmul-hw/.

Usage (from anywhere):
    python3 rtl/ntt_core/tools/gen_brom.py
"""

import argparse
import os
import sys

PE_TO_DIR = {1: "pe1", 4: "pe4", 16: "pe16"}

LICENSE = """/*
The designers:

Ahmet Can Mert <ahmetcanmert@sabanciuniv.edu>
Ferhat Yaman <ferhatyaman@sabanciuniv.edu>

To the extent possible under law, the implementer has waived all copyright
and related or neighboring rights to the source code in this file.
http://creativecommons.org/publicdomain/zero/1.0/
*/
"""

BANNER = """// read latency is 1 cc
//
// Generated by rtl/ntt_core/tools/gen_brom.py -- edit that script, not this file
// (except to re-run it; the tables below are verbatim copies of upstream).
//
// The twiddle tables differ per folding config and are not packings or
// contiguous slices of one another (rtl/folding_param_design.md section 3.3c).
// Extracting all three verbatim is the only bit-exact option; deriving them
// from a formula is not possible.  check_brom.py proves the extraction.
//
// The upstream files each carry a dead, never-referenced array declaration
//     (* rom_style="block" *) reg ... blockrom [...];
// It is dropped here (tracked in logs/ section 2B).

module ntt_BROM #(
    parameter PE_NUMBER = 1,          // 1 / 4 / 16: sets dout width (12*PE_NUMBER) and table
    parameter TW_ADDR_W = 9           // hand-picked 9/8/7, NOT a function of L (design doc 3.3)
)(
    input  wire                    clk,
    input  wire [TW_ADDR_W-1:0]    raddr,
    output reg  [12*PE_NUMBER-1:0] dout
);

generate
"""


def extract_case(path):
    with open(path, encoding="utf-8", errors="replace") as handle:
        lines = handle.read().split("\n")
    start = end = None
    for i, line in enumerate(lines):
        if start is None and line.strip().startswith("case(raddr)"):
            start = i
        if start is not None and line.strip() == "endcase":
            end = i
            break
    if start is None or end is None:
        raise SystemExit(f"{path}: no case/endcase block found")
    return lines[start:end + 1]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default_root = os.path.normpath(os.path.join(here, "..", ".."))  # rtl/
    ap = argparse.ArgumentParser()
    ap.add_argument("--src-root", default=default_root,
                    help="directory containing pe1/ pe4/ pe16/ (default: rtl/)")
    ap.add_argument("--out", default=os.path.normpath(os.path.join(here, "..", "BROM.v")),
                    help="output path (default: rtl/ntt_core/BROM.v)")
    args = ap.parse_args()

    parts = [LICENSE, BANNER]
    for n, pe in enumerate((1, 4, 16)):
        src = os.path.join(args.src_root, PE_TO_DIR[pe], "BROM.v")
        if not os.path.exists(src):
            raise SystemExit(f"missing upstream file: {src}")
        body = extract_case(src)
        parts.append(f"if (PE_NUMBER == {pe}) begin : G_TW{pe}\n")
        parts.append("    always @(posedge clk) begin\n")
        for line in body:
            parts.append(("    " + line + "\n") if line.strip() else "\n")
        parts.append("    end\n")
        parts.append("end else " if n < 2 else "end\n")
    parts.append("endgenerate\n\nendmodule\n")

    # LF line endings, always (repo convention 2: write bytes, never text mode)
    with open(args.out, "wb") as handle:
        handle.write("".join(parts).encode("utf-8"))

    print(f"wrote {args.out} ({os.path.getsize(args.out)} bytes)")
    print(f"source root: {args.src_root}")
    print("now run: python3 rtl/ntt_core/tools/check_brom.py")


if __name__ == "__main__":
    main()
